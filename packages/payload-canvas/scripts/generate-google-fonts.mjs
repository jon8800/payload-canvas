#!/usr/bin/env node
// Writes the Google Fonts family list for the theme's font picker (src/theme/admin/googleFonts.ts).
// Run from packages/payload-canvas: `pnpm generate:fonts`. Needs the google-font-metadata devDependency.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'

const require = createRequire(import.meta.url)
const data = JSON.parse(readFileSync(require.resolve('google-font-metadata/data/google-fonts-v2.json'), 'utf8'))
const families = Object.values(data)
  .map((font) => font.family)
  .toSorted((a, b) => a.localeCompare(b))

const out = path.resolve(import.meta.dirname, '../src/theme/admin/googleFonts.ts')
const body = [
  '// Generated by scripts/generate-google-fonts.mjs. Do not edit.',
  '/** Every Google Fonts family name, sorted. */',
  `export const GOOGLE_FONTS: readonly string[] = ${JSON.stringify(families)}`,
  '',
].join('\n')
writeFileSync(out, body)
console.log(`Wrote ${families.length} font families to ${out}`)
